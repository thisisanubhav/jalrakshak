import { test, expect } from '@playwright/test';
import { translate } from '../../src/field/i18n';
import { fieldNavigate } from './field-navigation';
const t=translate('en');

test('source state and district selectors work offline, persist and filter reports',async({page,context})=>{
  await page.goto('/personal');
  await page.getByRole('button',{name:t('add'),exact:true}).click();
  await expect(page.getByLabel(t('district'),{exact:true})).toBeDisabled();
  await page.getByLabel(t('state'),{exact:true}).selectOption('Himachal Pradesh');
  await page.getByLabel(t('district'),{exact:true}).selectOption('Kangra');
  await page.getByLabel(t('state'),{exact:true}).selectOption('Jharkhand');
  await expect(page.getByLabel(t('district'),{exact:true})).toHaveValue('');
  await page.getByLabel(t('state'),{exact:true}).selectOption('Himachal Pradesh');
  for(const [key,value] of [['code','INDIA-HP'],['name','Kangra pump'],['village','Village'],['operator','OP']] as const)await page.getByLabel(t(key),{exact:true}).fill(value);
  await expect(page.getByLabel(t('district'),{exact:true}).locator('option')).not.toContainText(['Khunti']);
  await page.getByLabel(t('district'),{exact:true}).selectOption('Kangra');
  await page.getByLabel(t('district'),{exact:true}).selectOption('Shimla');
  await page.getByLabel(t('district'),{exact:true}).selectOption('Kangra');
  await expect(page.getByLabel(t('district'),{exact:true})).toHaveValue('Kangra');
  await expect(page.getByText(t('locationSnapshot'),{exact:true})).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  const districtControl=page.getByLabel(t('district'),{exact:true});
  await expect(districtControl.locator('..')).toHaveClass('field-label');
  const controlBox=await districtControl.boundingBox();
  const labelBox=await districtControl.locator('..').boundingBox();
  expect(controlBox!.y).toBeGreaterThan(labelBox!.y+15);
  expect(controlBox!.height).toBeGreaterThanOrEqual(44);
  await page.screenshot({path:'test-results/acceptance/location-dropdowns-mobile.png',fullPage:true});
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;});await context.setOffline(true);
  await page.getByRole('button',{name:t('save'),exact:true}).click();
  await expect(page.getByRole('heading',{name:'INDIA-HP · Kangra pump',exact:true})).toBeVisible();
  await page.reload();await expect(page.getByText('Himachal Pradesh',{exact:true}).last()).toBeVisible();
  await page.getByLabel(t('filterState'),{exact:true}).selectOption('Himachal Pradesh');
  await page.getByLabel(t('filterDistrict'),{exact:true}).selectOption('Kangra');
  await expect(page.getByRole('heading',{name:'INDIA-HP · Kangra pump',exact:true})).toBeVisible();
  await fieldNavigate(page,'reports');
  await page.getByRole('button',{name:"Monthly reports",exact:true}).click();
  await page.getByLabel('Report state',{exact:true}).selectOption('Himachal Pradesh');
  await page.getByLabel('Report district',{exact:true}).selectOption('Kangra');
  await expect(page.getByTestId('monthly-report')).toContainText('Himachal Pradesh');
  await context.setOffline(false);
});

test('legacy sources keep district text until explicitly mapped to a state',async({page})=>{
  await page.goto('/personal');
  await page.getByText(t('bulkImport'),{exact:true}).click();
  await page.getByLabel(t('csvContent'),{exact:true}).fill('code,name,village,district,category,operator\nLEGACY,Old pump,Village,Old district spelling,WELL,OP\n');
  await page.getByRole('button',{name:t('csvPreview'),exact:true}).click();
  await page.getByRole('button',{name:t('csvConfirm'),exact:true}).click();
  await expect(page.getByRole('heading',{name:'LEGACY · Old pump',exact:true})).toBeVisible();
  await page.getByRole('button',{name:t('edit'),exact:true}).click();
  await expect(page.getByLabel(t('state'),{exact:true})).toHaveValue('');
  await expect(page.getByText(t('legacyLocation'),{exact:false})).toContainText('Old district spelling');
  await page.getByLabel(t('name'),{exact:true}).fill('Renamed pump');
  await page.getByRole('button',{name:t('save'),exact:true}).click();
  await expect(page.getByRole('heading',{name:'LEGACY · Renamed pump',exact:true})).toBeVisible();
  await expect(page.getByText('Old district spelling',{exact:true}).last()).toBeVisible();
  await page.getByRole('button',{name:t('edit'),exact:true}).click();
  await page.getByLabel(t('state'),{exact:true}).selectOption('Himachal Pradesh');
  await page.getByLabel(t('district'),{exact:true}).selectOption('Kangra');
  await page.getByRole('button',{name:t('save'),exact:true}).click();
  await expect(page.getByRole('heading',{name:'LEGACY · Renamed pump',exact:true})).toBeVisible();
  await expect(page.getByText('Himachal Pradesh',{exact:true}).last()).toBeVisible();
});
